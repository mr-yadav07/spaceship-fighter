package app.espcontrol.ui

data class FirmwareCandidate(
    val id: String,
    val type: String,
    val gpio: String,
    val leds: String = "64",
    val name: String = "",
)

object FirmwareCodeGenerator {
    private val presetEffects = listOf(1 to "Rainbow", 2 to "Pulse", 3 to "Color Cycle", 4 to "Chase")

    fun generate(deviceName: String, candidates: List<FirmwareCandidate>, enabledEffects: Set<Int> = presetEffects.map { it.first }.toSet()): String {
        val valid = candidates.isNotEmpty() && candidates.size <= 12 &&
            candidates.map { it.gpio.toIntOrNull() }.distinct().size == candidates.size &&
            candidates.all {
                val id = it.id.toIntOrNull()
                val pin = it.gpio.toIntOrNull()
                id != null && id in 0..255 && pin != null && pin in 0..39 &&
                    (it.type == "SWITCH" || (it.type == "RGB" && it.leds.toIntOrNull()?.let { n -> n in 1..65535 } == true))
            } && candidates.map { it.type to it.id }.distinct().size == candidates.size
        require(valid) { "Use 1–12 candidates, unique IDs per type and GPIO pins (0–39), and RGB LED counts from 1–65535." }
        val safeName = deviceName.filter { it.isLetterOrDigit() || it == '_' || it == '-' || it == ' ' }
            .take(32).ifBlank { "ESP32" }
        val rows = candidates.joinToString(",\n") { candidate ->
            val id = candidate.id.toInt()
            val pin = candidate.gpio.toInt()
            val name = candidate.name.filter { it.isLetterOrDigit() || it == '_' || it == '-' || it == ' ' }
                .take(24).ifBlank { "${candidate.type} $id" }
            if (candidate.type == "RGB") "  {RGB_KIND, $id, $pin, ${candidate.leds.toInt()}, \"$name\"}"
            else "  {SWITCH_KIND, $id, $pin, 0, \"$name\"}"
        }
        val selectedEffects = presetEffects.filter { it.first in enabledEffects }
        val effectRows = selectedEffects.joinToString(",\\n") { (id, name) -> "  {$id, \\"$name\\"}" }.ifBlank { "  {0,\\"\\"}" }
        return SOURCE.replace("@DEVICE@", safeName).replace("@CANDIDATES@", rows)
            .replace("@EFFECTS@", effectRows).replace("@EFFECT_COUNT@", selectedEffects.size.toString())
    }

    private val SOURCE = """
// Generated by ESP Control Studio · BLE Protocol v2 + smooth RGB transitions.
// Board: ESP32 Dev Module | Libraries: NimBLE-Arduino 2.x, Adafruit NeoPixel
#include <Arduino.h>
#include <NimBLEDevice.h>
#include <Adafruit_NeoPixel.h>
#include <vector>
#include <cstring>
#include <string>
#include <cmath>

static const char DEVICE_NAME[] = "@DEVICE@";
static constexpr char SERVICE_UUID[] = "a6c60001-6b9f-4d8e-a251-5bd248e8c101";
static constexpr char COMMAND_UUID[] = "a6c60002-6b9f-4d8e-a251-5bd248e8c101";
static constexpr char EVENTS_UUID[] = "a6c60003-6b9f-4d8e-a251-5bd248e8c101";
static constexpr uint8_t MAGIC0 = 0xEC, MAGIC1 = 0x53, VERSION = 2;

enum : uint8_t {
  CAPS_REQUEST = 0x01, CAPS = 0x02, SWITCH_SET = 0x10, RGB_SET = 0x11,
  EFFECT_SET = 0x12, RGB_TRANSITION = 0x13, UPDATE = 0x20,
  STATUS_REQUEST = 0x21, STATUS_MSG = 0x22
};
enum : uint8_t { SWITCH_KIND = 1, RGB_KIND = 2, EFFECT_KIND = 3 };

struct Candidate { uint8_t kind, id, pin; uint16_t leds; const char* name; };
struct Effect { uint8_t id; const char* name; };
static const Candidate CANDIDATES[] = {
@CANDIDATES@
};
static const Effect EFFECTS[] = {@EFFECTS@};
static constexpr size_t EFFECT_COUNT = @EFFECT_COUNT@;
static constexpr size_t CANDIDATE_COUNT = sizeof(CANDIDATES) / sizeof(CANDIDATES[0]);

struct State {
  uint8_t r=255, g=0, b=0, brightness=255, effect=0, speed=128;
  bool on=true, switchOn=false, transitioning=false;
  float fr=255, fg=0, fb=0, fbr=255;
  uint8_t tr=255, tg=0, tb=0, tbr=255;
  uint32_t startAt=0;
  uint16_t duration=0;
  Adafruit_NeoPixel* strip=nullptr;
};
static State states[CANDIDATE_COUNT];
static NimBLECharacteristic* eventChar=nullptr;
static volatile bool wantCaps=false, wantStatus=false;

struct Cmd {
  uint8_t kind=0, id=0, a=0, b=0, c=0, br=255, on=1;
  uint16_t duration=0, startDelay=0;
  bool transition=false;
};
static Cmd commandQueue[32];
static uint8_t queueCount=0;
static portMUX_TYPE queueMux = portMUX_INITIALIZER_UNLOCKED;
static std::vector<uint8_t> pendingFeedback;
static uint32_t feedbackDue=0;
static uint32_t lastTransitionFrame=0;

static uint16_t rd16(const uint8_t* p) { return uint16_t(p[0]) | (uint16_t(p[1]) << 8); }
static int indexOf(uint8_t kind, uint8_t id) {
  for (size_t i=0; i<CANDIDATE_COUNT; ++i)
    if (CANDIDATES[i].kind==kind && CANDIDATES[i].id==id) return (int)i;
  return -1;
}
static bool hasEffect(uint8_t id) {
  if (!id) return true;
  for (size_t i=0;i<EFFECT_COUNT;i++) if (EFFECTS[i].id==id) return true;
  return false;
}
static void sendFrame(uint8_t type, const std::vector<uint8_t>& payload) {
  if (!eventChar || payload.size()>508) return;
  std::vector<uint8_t> frame = {MAGIC0,MAGIC1,VERSION,type,(uint8_t)payload.size(),(uint8_t)(payload.size()>>8)};
  frame.insert(frame.end(),payload.begin(),payload.end());
  eventChar->setValue(frame.data(),frame.size());
  eventChar->notify();
}
static void queueState(uint8_t kind, uint8_t id, bool immediate=false) {
  int ix=indexOf(kind==EFFECT_KIND?RGB_KIND:kind,id);
  if (ix<0) return;
  size_t pos=0;
  while (pos<pendingFeedback.size()) {
    uint8_t k=pendingFeedback[pos];
    size_t n=k==SWITCH_KIND?3:(k==RGB_KIND?7:4);
    if (pos+n>pendingFeedback.size()) { pendingFeedback.clear(); break; }
    if (k==kind && pendingFeedback[pos+1]==id) {
      pendingFeedback.erase(pendingFeedback.begin()+pos,pendingFeedback.begin()+pos+n);
      break;
    }
    pos+=n;
  }
  State& s=states[ix];
  std::vector<uint8_t> entry={kind,id};
  if (kind==SWITCH_KIND) entry.push_back(s.switchOn?1:0);
  else if (kind==RGB_KIND) entry.insert(entry.end(),{s.r,s.g,s.b,s.brightness,(uint8_t)(s.on?1:0)});
  else entry.insert(entry.end(),{s.effect,s.speed});
  pendingFeedback.insert(pendingFeedback.end(),entry.begin(),entry.end());
  feedbackDue=immediate?millis():millis()+500;
}
static void sendCaps() {
  std::vector<uint8_t> p;
  size_t n=strlen(DEVICE_NAME);
  p.push_back((uint8_t)n); p.insert(p.end(),DEVICE_NAME,DEVICE_NAME+n);
  p.push_back((uint8_t)CANDIDATE_COUNT);
  for (const auto& c:CANDIDATES) {
    p.push_back(c.kind); p.push_back(c.id);
    if (c.kind==RGB_KIND) { p.push_back(c.leds&255); p.push_back(c.leds>>8); }
    n=strlen(c.name); p.push_back((uint8_t)n); p.insert(p.end(),c.name,c.name+n);
  }
  p.push_back((uint8_t)EFFECT_COUNT);
  for (size_t i=0;i<EFFECT_COUNT;i++) { const auto& e=EFFECTS[i]; p.push_back(e.id); n=strlen(e.name); p.push_back((uint8_t)n); p.insert(p.end(),e.name,e.name+n); }
  sendFrame(CAPS,p);
}
static void sendStatus() {
  std::vector<uint8_t> p={0};
  for (size_t i=0;i<CANDIDATE_COUNT;i++) {
    const auto& c=CANDIDATES[i]; const auto& s=states[i];
    p.push_back(c.kind); p.push_back(c.id);
    if (c.kind==SWITCH_KIND) p.push_back(s.switchOn?1:0);
    else p.insert(p.end(),{s.r,s.g,s.b,s.brightness,(uint8_t)(s.on?1:0)});
    p[0]++;
  }
  for (size_t i=0;i<CANDIDATE_COUNT;i++) if (CANDIDATES[i].kind==RGB_KIND) {
    p.push_back(EFFECT_KIND); p.push_back(CANDIDATES[i].id); p.push_back(states[i].effect); p.push_back(states[i].speed); p[0]++;
  }
  sendFrame(STATUS_MSG,p);
}
static bool validate(uint8_t type, const uint8_t* p, size_t n) {
  if (!n) return false;
  uint8_t count=p[0];
  size_t recordSize=type==SWITCH_SET?2:(type==RGB_SET?6:(type==EFFECT_SET?3:(type==RGB_TRANSITION?10:0)));
  if (!recordSize || n!=1+(size_t)count*recordSize) return false;
  size_t i=1;
  for (uint8_t k=0;k<count;k++) {
    uint8_t id=p[i++];
    if (type==SWITCH_SET) {
      uint8_t v=p[i++];
      if (indexOf(SWITCH_KIND,id)<0 || v>1) return false;
    } else if (type==RGB_SET) {
      i+=4; uint8_t on=p[i++];
      if (indexOf(RGB_KIND,id)<0 || on>1) return false;
    } else if (type==RGB_TRANSITION) {
      i+=4; uint8_t on=p[i++]; uint16_t duration=rd16(p+i); i+=2; uint16_t delay=rd16(p+i); i+=2;
      if (indexOf(RGB_KIND,id)<0 || on>1 || duration>5000 || delay>1000) return false;
    } else {
      uint8_t effect=p[i++]; i++;
      if (indexOf(RGB_KIND,id)<0 || !hasEffect(effect)) return false;
    }
  }
  return i==n;
}
static void enqueue(void* input) {
  const Cmd& cmd=*static_cast<const Cmd*>(input);
  portENTER_CRITICAL(&queueMux);
  for (uint8_t i=0;i<queueCount;i++) {
    if (commandQueue[i].kind==cmd.kind && commandQueue[i].id==cmd.id) {
      commandQueue[i]=cmd;
      portEXIT_CRITICAL(&queueMux);
      return;
    }
  }
  if (queueCount<32) commandQueue[queueCount++]=cmd;
  portEXIT_CRITICAL(&queueMux);
}
static bool dequeue(void* output) {
  Cmd& cmd=*static_cast<Cmd*>(output);
  bool found=false;
  portENTER_CRITICAL(&queueMux);
  if (queueCount) {
    cmd=commandQueue[0];
    for (uint8_t i=1;i<queueCount;i++) commandQueue[i-1]=commandQueue[i];
    queueCount--; found=true;
  }
  portEXIT_CRITICAL(&queueMux);
  return found;
}
static void onCommand(const uint8_t* d, size_t n) {
  if (n<6 || d[0]!=MAGIC0 || d[1]!=MAGIC1 || d[2]!=VERSION || rd16(d+4)!=n-6) return;
  uint8_t type=d[3]; const uint8_t* p=d+6; size_t len=n-6;
  if (type==CAPS_REQUEST && len==0) { wantCaps=true; return; }
  if (type==STATUS_REQUEST && len==0) { wantStatus=true; return; }
  if (!validate(type,p,len)) return;
  size_t i=1;
  for (uint8_t k=0;k<p[0];k++) {
    Cmd c{}; c.id=p[i++];
    if (type==SWITCH_SET) { c.kind=SWITCH_KIND; c.a=p[i++]; }
    else if (type==RGB_SET) {
      c.kind=RGB_KIND; c.a=p[i++]; c.b=p[i++]; c.c=p[i++]; c.br=p[i++]; c.on=p[i++];
    } else if (type==RGB_TRANSITION) {
      c.kind=RGB_KIND; c.transition=true;
      c.a=p[i++]; c.b=p[i++]; c.c=p[i++]; c.br=p[i++]; c.on=p[i++];
      c.duration=rd16(p+i); i+=2; c.startDelay=rd16(p+i); i+=2;
    } else { c.kind=EFFECT_KIND; c.a=p[i++]; c.b=p[i++]; }
    enqueue(&c);
  }
}
class Callbacks : public NimBLECharacteristicCallbacks {
  void onWrite(NimBLECharacteristic* characteristic, NimBLEConnInfo&) override {
    auto value=characteristic->getValue();
    onCommand((const uint8_t*)value.data(),value.size());
  }
};
static void renderRgb(void* state, const void* config) {
  State& s=*static_cast<State*>(state);
  const Candidate& cfg=*static_cast<const Candidate*>(config);
  if (!s.strip) return;
  s.strip->fill(s.on?s.strip->Color(s.r,s.g,s.b):0);
  s.strip->setBrightness(s.brightness);
  s.strip->show();
}
static void updateTransition(void* state, const void* config, uint32_t now) {
  State& s=*static_cast<State*>(state);
  const Candidate& cfg=*static_cast<const Candidate*>(config);
  if (!s.transitioning) return;
  if ((int32_t)(now-s.startAt)<0) return;
  float t=s.duration==0?1.0f:min(1.0f,(float)(now-s.startAt)/(float)s.duration);
  s.r=(uint8_t)(s.fr+((float)s.tr-s.fr)*t+0.5f);
  s.g=(uint8_t)(s.fg+((float)s.tg-s.fg)*t+0.5f);
  s.b=(uint8_t)(s.fb+((float)s.tb-s.fb)*t+0.5f);
  s.brightness=(uint8_t)(s.fbr+((float)s.tbr-s.fbr)*t+0.5f);
  renderRgb(&s,&cfg);
  if (t>=1.0f) { s.transitioning=false; queueState(RGB_KIND,cfg.id,true); }
}
static void applyQueued() {
  Cmd c;
  while (dequeue(&c)) {
    int ix=indexOf(c.kind,c.id); if (ix<0) continue;
    State& s=states[ix]; const Candidate& cfg=CANDIDATES[ix];
    if (c.kind==SWITCH_KIND) {
      s.switchOn=c.a; digitalWrite(cfg.pin,s.switchOn?HIGH:LOW);
      queueState(c.kind,c.id);
    } else if (c.kind==RGB_KIND) {
      updateTransition(&s,&cfg,millis());
      s.effect=0;
      if (c.transition) {
        s.fr=s.r; s.fg=s.g; s.fb=s.b; s.fbr=s.brightness;
        s.tr=c.a; s.tg=c.b; s.tb=c.c; s.tbr=c.br; s.on=c.on;
        s.duration=c.duration;
        // First frame gets a shared start offset. Updates during a running fade apply immediately.
        uint16_t delay=s.transitioning?0:c.startDelay;
        s.startAt=millis()+delay;
        s.transitioning=true;
        if (!s.duration) updateTransition(&s,&cfg,s.startAt);
      } else {
        s.r=c.a; s.g=c.b; s.b=c.c; s.brightness=c.br; s.on=c.on; s.transitioning=false;
        renderRgb(&s,&cfg); queueState(RGB_KIND,c.id);
      }
    } else {
      s.effect=c.a; s.speed=c.b;
      if (!s.effect) renderRgb(&s,&cfg);
      queueState(EFFECT_KIND,c.id);
    }
  }
}
static void runTransitions() {
  uint32_t now=millis();
  if (now-lastTransitionFrame<16) return;
  lastTransitionFrame=now;
  for (size_t i=0;i<CANDIDATE_COUNT;i++) {
    if (CANDIDATES[i].kind==RGB_KIND) updateTransition(&states[i],&CANDIDATES[i],now);
  }
}
static void runEffects() {
  static uint32_t last=0;
  uint32_t now=millis(); if (now-last<20) return; last=now;
  for (size_t i=0;i<CANDIDATE_COUNT;i++) {
    if (CANDIDATES[i].kind!=RGB_KIND) continue;
    State& s=states[i]; if (!s.strip || !s.effect || s.transitioning) continue;
    auto& strip=*s.strip;
    if (s.effect==1) {
      for (uint16_t j=0;j<CANDIDATES[i].leds;j++) strip.setPixelColor(j,strip.ColorHSV((uint16_t)(now*s.speed+j*65535/CANDIDATES[i].leds)));
    } else if (s.effect==2) {
      uint8_t v=(uint8_t)((std::sin(now/500.0)+1.0)*127.5);
      strip.fill(strip.Color(s.r*v/255,s.g*v/255,s.b*v/255));
    } else if (s.effect==3) {
      strip.fill(strip.Color((now/8)%255,(now/8+85)%255,(now/8+170)%255));
    } else if (s.effect==4) {
      strip.clear(); strip.setPixelColor((now/max(1,(int)(255-s.speed)))%CANDIDATES[i].leds,strip.Color(s.r,s.g,s.b));
    }
    strip.setBrightness(s.brightness); strip.show();
  }
}
static void flushFeedback() {
  if (pendingFeedback.empty() || (int32_t)(millis()-feedbackDue)<0) return;
  std::vector<uint8_t> p={0}; size_t i=0;
  while (i<pendingFeedback.size()) {
    uint8_t kind=pendingFeedback[i]; size_t n=kind==SWITCH_KIND?3:(kind==RGB_KIND?7:4);
    if (i+n>pendingFeedback.size() || p.size()+n>508) break;
    p.insert(p.end(),pendingFeedback.begin()+i,pendingFeedback.begin()+i+n); i+=n; p[0]++;
  }
  if (p[0]) sendFrame(UPDATE,p);
  pendingFeedback.erase(pendingFeedback.begin(),pendingFeedback.begin()+i);
  if (!pendingFeedback.empty()) feedbackDue=millis()+10;
}
void setup() {
  Serial.begin(115200);
  for (size_t i=0;i<CANDIDATE_COUNT;i++) {
    const Candidate& c=CANDIDATES[i];
    if (c.kind==SWITCH_KIND) { pinMode(c.pin,OUTPUT); states[i].switchOn=false; digitalWrite(c.pin,LOW); }
    else {
      states[i].strip=new Adafruit_NeoPixel(c.leds,c.pin,NEO_GRB+NEO_KHZ800);
      states[i].strip->begin(); states[i].strip->clear(); states[i].strip->show();
    }
  }
  char advName[18];
  snprintf(advName,sizeof(advName),"ESPC-%012llX",(unsigned long long)(ESP.getEfuseMac()&0xFFFFFFFFFFFFULL));
  NimBLEDevice::init(std::string(advName)); NimBLEDevice::setMTU(517);
  NimBLEServer* server=NimBLEDevice::createServer();
  NimBLEService* service=server->createService(SERVICE_UUID);
  auto* command=service->createCharacteristic(COMMAND_UUID,NIMBLE_PROPERTY::WRITE|NIMBLE_PROPERTY::WRITE_NR);
  eventChar=service->createCharacteristic(EVENTS_UUID,NIMBLE_PROPERTY::NOTIFY);
  command->setCallbacks(new Callbacks()); service->start();
  auto* advertising=NimBLEDevice::getAdvertising(); advertising->addServiceUUID(SERVICE_UUID); advertising->start();
}
void loop() {
  if (wantCaps) { wantCaps=false; sendCaps(); }
  if (wantStatus) { wantStatus=false; sendStatus(); }
  applyQueued(); runTransitions(); runEffects(); flushFeedback();
  delay(1);
}
""".trimIndent()
}
