package app.espcontrol.ui

data class FirmwareCandidate(
    val id: String,
    val type: String,
    val gpio: String,
    val leds: String = "64",
    val name: String = "",
)

object FirmwareCodeGenerator {
    fun generate(deviceName: String, candidates: List<FirmwareCandidate>): String {
        val valid = candidates.isNotEmpty() && candidates.all {
            val id=it.id.toIntOrNull(); val pin=it.gpio.toIntOrNull()
            id!=null && id in 0..255 && pin!=null && pin in 0..48 &&
                (it.type=="SWITCH" || (it.type=="RGB" && it.leds.toIntOrNull()?.let { n -> n in 1..65535 } == true))
        } && candidates.map { it.type to it.id }.distinct().size==candidates.size
        require(valid) { "Candidate IDs, GPIO pins or LED counts are invalid or duplicated." }
        val safeName=deviceName.replace("\\","").replace("\"","").take(32).ifBlank { "ESP32" }
        val rows=candidates.joinToString(",\n") { c ->
            val id=c.id.toInt()
            val pin=c.gpio.toInt()
            val name=(c.name.ifBlank { "${c.type} $id" }).replace("\\","").replace("\"","").take(24)
            if(c.type=="RGB") "  {RGB_KIND, $id, $pin, ${c.leds.toInt()}, \"$name\"}"
            else "  {SWITCH_KIND, $id, $pin, 0, \"$name\"}"
        }
        return SOURCE.replace("@DEVICE@",safeName).replace("@CANDIDATES@",rows)
    }

    private val SOURCE = """
// Generated by ESP Control Studio. Select ESP32 Dev Module and upload.
// Libraries: NimBLE-Arduino 2.x, Adafruit NeoPixel.
#include <Arduino.h>
#include <NimBLEDevice.h>
#include <Adafruit_NeoPixel.h>
#include <vector>
#include <mutex>

static const char DEVICE_NAME[]="@DEVICE@";
static constexpr char SERVICE_UUID[]="a6c60001-6b9f-4d8e-a251-5bd248e8c101";
static constexpr char COMMAND_UUID[]="a6c60002-6b9f-4d8e-a251-5bd248e8c101";
static constexpr char EVENTS_UUID[]="a6c60003-6b9f-4d8e-a251-5bd248e8c101";
static constexpr uint8_t MAGIC0=0xEC,MAGIC1=0x53,VERSION=2;
enum:uint8_t{CAPS_REQUEST=1,CAPS=2,SWITCH_SET=16,RGB_SET=17,EFFECT_SET=18,UPDATE=32,STATUS_REQUEST=33,STATUS_MSG=34};
enum:uint8_t{SWITCH_KIND=1,RGB_KIND=2,EFFECT_KIND=3};
struct Candidate{uint8_t kind,id;uint8_t pin;uint16_t leds;const char*name;};
struct Effect{uint8_t id;const char*name;};
static const Candidate CANDIDATES[]={
@CANDIDATES@
};
static const Effect EFFECTS[]={{1,"Rainbow"},{2,"Pulse"},{3,"Color Cycle"},{4,"Chase"}};
struct State{uint8_t r=255,g=0,b=0,brightness=255,effect=0,speed=128;bool on=true,switchOn=false;Adafruit_NeoPixel* strip=nullptr;};
static State states[sizeof(CANDIDATES)/sizeof(CANDIDATES[0])];
static NimBLECharacteristic* eventChar=nullptr;
static std::vector<uint8_t> pending;
static uint32_t feedbackDue=0;
struct Cmd{uint8_t kind,id,a,b,c,br,on;};
static std::vector<Cmd> queue;
static std::mutex queueMutex;
static int indexOf(uint8_t kind,uint8_t id){for(size_t i=0;i<sizeof(CANDIDATES)/sizeof(CANDIDATES[0]);i++)if(CANDIDATES[i].kind==kind&&CANDIDATES[i].id==id)return (int)i;return -1;}
static bool hasEffect(uint8_t id){if(!id)return true;for(auto&e:EFFECTS)if(e.id==id)return true;return false;}
static uint16_t rd16(const uint8_t*p){return uint16_t(p[0])|(uint16_t(p[1])<<8);}
static void sendFrame(uint8_t type,const std::vector<uint8_t>&p){if(!eventChar||p.size()>508)return;std::vector<uint8_t>f={MAGIC0,MAGIC1,VERSION,type,uint8_t(p.size()),uint8_t(p.size()>>8)};f.insert(f.end(),p.begin(),p.end());eventChar->setValue(f.data(),f.size());eventChar->notify();}
static void queueState(uint8_t kind,uint8_t id){
 int ix=indexOf(kind,id);if(ix<0)return;
 size_t pos=0;while(pos<pending.size()){uint8_t k=pending[pos];size_t n=k==SWITCH_KIND?3:(k==RGB_KIND?7:4);if(pos+n>pending.size()){pending.clear();break;}if(k==kind&&pending[pos+1]==id){pending.erase(pending.begin()+pos,pending.begin()+pos+n);break;}pos+=n;}
 State&s=states[ix];std::vector<uint8_t>e={kind,id};
 if(kind==SWITCH_KIND)e.push_back(s.switchOn?1:0);
 else if(kind==RGB_KIND)e.insert(e.end(),{s.r,s.g,s.b,s.brightness,uint8_t(s.on)});
 else e.insert(e.end(),{s.effect,s.speed});
 pending.insert(pending.end(),e.begin(),e.end());feedbackDue=millis()+500;
}
static void sendCaps(){
 std::vector<uint8_t>p;size_t n=strlen(DEVICE_NAME);p.push_back(n);p.insert(p.end(),DEVICE_NAME,DEVICE_NAME+n);
 constexpr size_t count=sizeof(CANDIDATES)/sizeof(CANDIDATES[0]);if(count>255)return;p.push_back(count);
 for(auto&c:CANDIDATES){p.push_back(c.kind);p.push_back(c.id);if(c.kind==RGB_KIND){p.push_back(c.leds&255);p.push_back(c.leds>>8);}n=strlen(c.name);p.push_back(n);p.insert(p.end(),c.name,c.name+n);}
 p.push_back(sizeof(EFFECTS)/sizeof(EFFECTS[0]));for(auto&e:EFFECTS){p.push_back(e.id);n=strlen(e.name);p.push_back(n);p.insert(p.end(),e.name,e.name+n);}sendFrame(CAPS,p);
}
static void sendStatus(){
 std::vector<uint8_t>p={0};for(size_t i=0;i<sizeof(CANDIDATES)/sizeof(CANDIDATES[0]);i++){auto&c=CANDIDATES[i];auto&s=states[i];p.push_back(c.kind);p.push_back(c.id);if(c.kind==SWITCH_KIND)p.push_back(s.switchOn);else p.insert(p.end(),{s.r,s.g,s.b,s.brightness,uint8_t(s.on)});p[0]++;}
 for(size_t i=0;i<sizeof(CANDIDATES)/sizeof(CANDIDATES[0]);i++)if(CANDIDATES[i].kind==RGB_KIND){p.push_back(EFFECT_KIND);p.push_back(CANDIDATES[i].id);p.push_back(states[i].effect);p.push_back(states[i].speed);p[0]++;}
 sendFrame(STATUS_MSG,p);
}
static bool validate(uint8_t type,const uint8_t*p,size_t n){
 if(!n)return false;uint8_t count=p[0];size_t sz=type==SWITCH_SET?2:(type==RGB_SET?6:(type==EFFECT_SET?3:0));if(!sz||n!=1+count*sz)return false;
 size_t i=1;for(uint8_t k=0;k<count;k++){uint8_t id=p[i++];if(type==SWITCH_SET){uint8_t v=p[i++];if(indexOf(SWITCH_KIND,id)<0||v>1)return false;}else if(type==RGB_SET){i+=4;uint8_t on=p[i++];if(indexOf(RGB_KIND,id)<0||on>1)return false;}else{uint8_t e=p[i++];i++;if(indexOf(RGB_KIND,id)<0||!hasEffect(e))return false;}}return i==n;
}
static void enqueue(Cmd c){std::lock_guard<std::mutex>g(queueMutex);for(auto&q:queue)if(q.kind==c.kind&&q.id==c.id){q=c;return;}queue.push_back(c);}
static void onCommand(const uint8_t*d,size_t n){
 if(n<6||d[0]!=MAGIC0||d[1]!=MAGIC1||d[2]!=VERSION||rd16(d+4)!=n-6)return;uint8_t type=d[3];const uint8_t*p=d+6;size_t len=n-6;
 if(type==CAPS_REQUEST&&len==0){sendCaps();return;}if(type==STATUS_REQUEST&&len==0){sendStatus();return;}if(!validate(type,p,len))return;
 size_t i=1;for(uint8_t k=0;k<p[0];k++){Cmd c{};c.id=p[i++];if(type==SWITCH_SET){c.kind=SWITCH_KIND;c.a=p[i++];}else if(type==RGB_SET){c.kind=RGB_KIND;c.a=p[i++];c.b=p[i++];c.c=p[i++];c.br=p[i++];c.on=p[i++];}else{c.kind=EFFECT_KIND;c.a=p[i++];c.b=p[i++];}enqueue(c);}
}
class Callbacks:public NimBLECharacteristicCallbacks{void onWrite(NimBLECharacteristic*c,NimBLEConnInfo&)override{auto v=c->getValue();onCommand((const uint8_t*)v.data(),v.size());}};
static void applyQueued(){
 Cmd c{};{std::lock_guard<std::mutex>g(queueMutex);if(queue.empty())return;c=queue.front();queue.erase(queue.begin());}
 uint8_t kind=c.kind;int ix=indexOf(kind,c.id);if(ix<0)return;State&s=states[ix];const Candidate&cfg=CANDIDATES[ix];
 if(kind==SWITCH_KIND){s.switchOn=c.a;digitalWrite(cfg.pin,s.switchOn?HIGH:LOW);}
 else if(kind==RGB_KIND){s.r=c.a;s.g=c.b;s.b=c.c;s.brightness=c.br;s.on=c.on;if(s.strip){for(uint16_t j=0;j<cfg.leds;j++)s.strip->setPixelColor(j,s.on?s.strip->Color(s.r,s.g,s.b):0);s.strip->setBrightness(s.brightness);s.strip->show();}}
 else{s.effect=c.a;s.speed=c.b;}
 queueState(kind,c.id);
}
static void runEffects(){
 static uint32_t last=0;if(millis()-last<20)return;last=millis();
 for(size_t i=0;i<sizeof(CANDIDATES)/sizeof(CANDIDATES[0]);i++){if(CANDIDATES[i].kind!=RGB_KIND||!states[i].effect||!states[i].strip)continue;State&s=states[i];auto&strip=*s.strip;
 if(s.effect==1){for(uint16_t j=0;j<CANDIDATES[i].leds;j++)strip.setPixelColor(j,strip.ColorHSV((uint16_t)(millis()*s.speed+j*65535/CANDIDATES[i].leds)));strip.setBrightness(s.brightness);strip.show();}
 else if(s.effect==2){uint8_t v=(sin(millis()/500.0)+1)*127;strip.fill(strip.Color(s.r*v/255,s.g*v/255,s.b*v/255));strip.setBrightness(s.brightness);strip.show();}
 else if(s.effect==3){strip.fill(strip.Color((millis()/8)%255,(millis()/8+85)%255,(millis()/8+170)%255));strip.setBrightness(s.brightness);strip.show();}
 else if(s.effect==4){strip.clear();strip.setPixelColor((millis()/max(1,(int)(255-s.speed)))%CANDIDATES[i].leds,strip.Color(s.r,s.g,s.b));strip.setBrightness(s.brightness);strip.show();}
 }
}
static void flushFeedback(){if(pending.empty()||(int32_t)(millis()-feedbackDue)<0)return;std::vector<uint8_t>p={0};size_t i=0;while(i<pending.size()){uint8_t k=pending[i];size_t n=k==SWITCH_KIND?3:(k==RGB_KIND?7:4);if(i+n>pending.size()||p.size()+n>508)break;p.insert(p.end(),pending.begin()+i,pending.begin()+i+n);i+=n;p[0]++;}if(p[0])sendFrame(UPDATE,p);pending.erase(pending.begin(),pending.begin()+i);if(!pending.empty())feedbackDue=millis()+10;}
void setup(){
 Serial.begin(115200);for(size_t i=0;i<sizeof(CANDIDATES)/sizeof(CANDIDATES[0]);i++){const Candidate&c=CANDIDATES[i];if(c.kind==SWITCH_KIND){pinMode(c.pin,OUTPUT);states[i].switchOn=false;digitalWrite(c.pin,LOW);}else{states[i].strip=new Adafruit_NeoPixel(c.leds,c.pin,NEO_GRB+NEO_KHZ800);states[i].strip->begin();states[i].strip->clear();states[i].strip->show();}}
 char advName[18];snprintf(advName,sizeof(advName),"ESPC-%012llX",(unsigned long long)(ESP.getEfuseMac()&0xFFFFFFFFFFFFULL));NimBLEDevice::init(std::string(advName));NimBLEDevice::setMTU(517);
 NimBLEServer*server=NimBLEDevice::createServer();NimBLEService*svc=server->createService(SERVICE_UUID);
 auto*cmd=svc->createCharacteristic(COMMAND_UUID,NIMBLE_PROPERTY::WRITE|NIMBLE_PROPERTY::WRITE_NR);eventChar=svc->createCharacteristic(EVENTS_UUID,NIMBLE_PROPERTY::NOTIFY);cmd->setCallbacks(new Callbacks());svc->start();auto*adv=NimBLEDevice::getAdvertising();adv->addServiceUUID(SERVICE_UUID);adv->start();
}
void loop(){applyQueued();runEffects();flushFeedback();delay(1);}
""".trimIndent()
}
